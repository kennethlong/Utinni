        private static string ResolveGeneratedPath(string explicitPath)
        {
            if (!string.IsNullOrEmpty(explicitPath)) return explicitPath;

            string env = Environment.GetEnvironmentVariable("UTINNI_GENERATED_CS");
            if (!string.IsNullOrEmpty(env)) return env;

            // Probe walk-up from the current directory for UtinniCoreDotNet/Generated/UtinniCore.cs.
            var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
            while (dir != null)
            {
                string candidate = Path.Combine(dir.FullName, "UtinniCoreDotNet", "Generated", "UtinniCore.cs");
                if (File.Exists(candidate)) return candidate;
                dir = dir.Parent;
            }
            throw new FileNotFoundException(
                "Could not resolve Generated/UtinniCore.cs (set UTINNI_GENERATED_CS or run from the repo tree).");
        }

        private static string ResolveBaselinePath(string explicitPath, string resolvedGeneratedPath = null)
        {
            if (!string.IsNullOrEmpty(explicitPath)) return explicitPath;

            string env = Environment.GetEnvironmentVariable("UTINNI_ABI_BASELINE");
            if (!string.IsNullOrEmpty(env)) return env;

            // WR-06: co-anchor to the resolved generated file's repo root. The generated path is
            // <repoRoot>/UtinniCoreDotNet/Generated/UtinniCore.cs, so its repo root is three
            // directories up. Forming the baseline path relative to THAT root (rather than
            // independently walking from cwd and returning the first ancestor whose Fixtures dir
            // merely exists) guarantees the re-blessed baseline lands in the same tree as the
            // regen source — never a sibling checkout.
            if (!string.IsNullOrEmpty(resolvedGeneratedPath))
            {
                try
                {
                    // .../Generated/UtinniCore.cs -> Generated -> UtinniCoreDotNet -> <repoRoot>
                    string repoRoot = Path.GetDirectoryName(   // <repoRoot>
                        Path.GetDirectoryName(                  // <repoRoot>/UtinniCoreDotNet
                            Path.GetDirectoryName(              // .../UtinniCoreDotNet/Generated
                                Path.GetFullPath(resolvedGeneratedPath))));
                    if (!string.IsNullOrEmpty(repoRoot))
                    {
                        return Path.Combine(
                            repoRoot, "UtinniCoreDotNet.Tests", "Fixtures", "abi-baseline-blockhashes.txt");
                    }
                }
                catch
                {
                    // Fall through to the file-existence probe below.
                }
            }

            // Fallback: mirror ResolveGeneratedPath — walk up and require the baseline FILE to
            // exist (not merely its containing directory), so an unexpected cwd cannot resolve to
            // a wrong-tree directory that merely happens to have a Fixtures folder.
            var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
            while (dir != null)
            {
                string candidate = Path.Combine(
                    dir.FullName, "UtinniCoreDotNet.Tests", "Fixtures", "abi-baseline-blockhashes.txt");
                if (File.Exists(candidate)) return candidate;
                dir = dir.Parent;
            }
            throw new FileNotFoundException(
                "Could not resolve the baseline file (set UTINNI_ABI_BASELINE or run from the repo tree).");
        }
